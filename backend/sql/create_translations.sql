create table if not exists public.translations (
  id uuid primary key default gen_random_uuid(),
  translation_key text not null,
  locale text not null check (locale in ('en', 'ru', 'kk')),
  value text not null,
  namespace text not null default 'common',
  created_at timestamptz not null default now(),
  unique (translation_key, locale)
);

create index if not exists translations_locale_idx on public.translations (locale);
create index if not exists translations_key_idx on public.translations (translation_key);

alter table public.translations enable row level security;

